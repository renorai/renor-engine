/**
 * Experiment: does Bun run the engine faster or lighter than Node 22? Measurement only; Node stays the runtime.
 *
 *   npm run build            # path A runs the compiled dist/cli.js
 *   node_modules/.bin/tsx scripts/bench/bun-vs-node.ts [--runs 10] [--calls 1000] [--fixture <dir>] [--out result.json]
 *
 * Path A  `renor-engine mcp` over stdio (compiled dist/cli.js): process spawn -> first tools/list answer (ms),
 *         VmRSS after start, VmRSS after N `search` calls.
 * Path B  the mvp surface, in-process (scripts/bench/mcp-latency.ts openWorkspace): module load + open -> first
 *         tools/list (ms), RSS after start and after N `get_context` calls, per-call p50/p95.
 * Runs alternate node, bun, node, bun ... on the same machine. Each run works on a fresh copy of the fixture
 * (default: the 1,429-note hash-768 fixture generated by mcp-latency.ts --sizes 1429 --dir <d>).
 * Path B children run from TypeScript source: tsx under Node, native under Bun (so their load time is not a runtime comparison;
 * path A's compiled dist is). Synthetic data only.
 */
import fs from 'fs';
import os from 'os';
import path from 'path';
import { spawn, spawnSync, type ChildProcess } from 'child_process';

const rssMb = (pid: number): number => {
  const m = /VmRSS:\s+(\d+) kB/.exec(fs.readFileSync(`/proc/${pid}/status`, 'utf8'));
  return m ? Number(m[1]) / 1024 : NaN;
};
const pct = (xs: number[], p: number): number => { const s = [...xs].sort((a, b) => a - b); return s[Math.min(s.length - 1, Math.floor(p * s.length))]; };
const copy = (src: string): string => { const d = fs.mkdtempSync(path.join(os.tmpdir(), 'bvn-')); fs.cpSync(src, d, { recursive: true }); return d; };

async function childB(): Promise<void> {
  const t0 = performance.now();
  const { openWorkspace } = await import('./mcp-latency.js');
  const { EvalHashEmbeddingProvider } = await import('../../src/eval/hashEmbedding.js');
  const dir = process.env.BVN_DIR!;
  const n = Number(process.env.BVN_CALLS);
  const auth = fs.mkdtempSync(path.join(os.tmpdir(), 'bvn-auth-'));
  const ws = await openWorkspace(dir, Object.assign(new EvalHashEmbeddingProvider(), { dimensions: 768 }), auth);
  await ws.client.listTools();
  const startMs = performance.now() - t0;
  const rssStart = rssMb(process.pid);
  const queries = ['what did we decide about billing for project-12', 'status of the gateway rollout and the incident follow-ups', 'who is Rowan and what is my current project', 'project-7 status owner deadline', 'what was the pricing decision previously'];
  const lat: number[] = [];
  for (let i = 0; i < n; i++) {
    const t = performance.now();
    await ws.client.callTool({ name: 'get_context', arguments: { query: queries[i % queries.length] } });
    lat.push(performance.now() - t);
  }
  const rssEnd = rssMb(process.pid);
  process.stdout.write('BVN ' + JSON.stringify({ startMs, rssStart, rssEnd, p50: pct(lat, 0.5), p95: pct(lat, 0.95) }) + '\n');
  await ws.close();
  process.exit(0);
}

function rpc(child: ChildProcess) {
  let buf = ''; const waiters = new Map<number, (m: any) => void>();
  child.stdout!.on('data', d => { buf += d; let i; while ((i = buf.indexOf('\n')) >= 0) { const l = buf.slice(0, i); buf = buf.slice(i + 1); try { const m = JSON.parse(l); waiters.get(m.id)?.(m); } catch { /* log line */ } } });
  let id = 0;
  return {
    call: (method: string, params: unknown = {}) => new Promise<any>((res, rej) => { const k = ++id; const to = setTimeout(() => rej(new Error('timeout ' + method)), 60000); waiters.set(k, m => { clearTimeout(to); res(m); }); child.stdin!.write(JSON.stringify({ jsonrpc: '2.0', id: k, method, params }) + '\n'); }),
    note: (method: string) => child.stdin!.write(JSON.stringify({ jsonrpc: '2.0', method }) + '\n'),
  };
}

async function runA(rt: string, fixture: string, n: number) {
  const dir = copy(fixture);
  const t0 = performance.now();
  const child = spawn(rt, [path.resolve(__dirname, '../../dist/cli.js'), 'mcp'], { cwd: dir, env: { ...process.env, VAULT_PATH: dir, RENOR_TELEMETRY: 'off', RENOR_SHARING: 'off' }, stdio: ['pipe', 'pipe', 'ignore'] });
  const r = rpc(child);
  await r.call('initialize', { protocolVersion: '2024-11-05', capabilities: {}, clientInfo: { name: 'bvn', version: '0' } });
  r.note('notifications/initialized');
  const tools = await r.call('tools/list');
  const startMs = performance.now() - t0;
  const names: string[] = tools.result.tools.map((t: any) => t.name);
  const rssStart = rssMb(child.pid!);
  const lat: number[] = [];
  for (let i = 0; i < n; i++) { const t = performance.now(); await r.call('tools/call', { name: 'search', arguments: { query: `project ${i % 50} deploy logging` } }); lat.push(performance.now() - t); }
  const rssEnd = rssMb(child.pid!);
  child.kill(); fs.rmSync(dir, { recursive: true, force: true });
  return { startMs, rssStart, rssEnd, p50: pct(lat, 0.5), p95: pct(lat, 0.95), tools: names.length };
}

function runB(rt: string, fixture: string, n: number) {
  const dir = copy(fixture);
  const cmd = rt === 'bun' ? ['bun', __filename] : [path.resolve(__dirname, '../../node_modules/.bin/tsx'), __filename];
  const p = spawnSync(cmd[0], cmd.slice(1), { env: { ...process.env, BVN_CHILD: 'B', BVN_DIR: dir, BVN_CALLS: String(n) }, encoding: 'utf8', timeout: 600000 });
  fs.rmSync(dir, { recursive: true, force: true });
  const line = p.stdout.split('\n').find(l => l.startsWith('BVN '));
  if (!line) throw new Error(`path B under ${rt} failed: ${(p.stderr || p.stdout).slice(-600)}`);
  return JSON.parse(line.slice(4));
}

async function main() {
  const a = process.argv; const opt = (k: string, d: string) => (a.includes(k) ? a[a.indexOf(k) + 1] : d);
  const runs = Number(opt('--runs', '10')), calls = Number(opt('--calls', '1000'));
  const fixture = opt('--fixture', '/tmp/bvn-fixture/n1429-hash768');
  const out: Record<string, Record<string, any[]>> = { A: { node: [], bun: [] }, B: { node: [], bun: [] } };
  for (let i = 0; i < runs; i++) for (const rt of ['node', 'bun']) {
    out.A[rt].push(await runA(rt, fixture, calls));
    out.B[rt].push(runB(rt, fixture, calls));
    console.error(`run ${i + 1}/${runs} ${rt} done`);
  }
  const med = (xs: number[]) => pct(xs, 0.5);
  const summary: Record<string, any> = { runs, calls, node: process.version, bun: spawnSync('bun', ['-v'], { encoding: 'utf8' }).stdout.trim(), cpus: os.cpus().length };
  for (const P of ['A', 'B']) for (const rt of ['node', 'bun']) {
    const r = out[P][rt]; summary[`${P}-${rt}`] = Object.fromEntries(['startMs', 'rssStart', 'rssEnd', 'p50', 'p95'].map(k => [k, +med(r.map((x: any) => x[k])).toFixed(1)]));
  }
  const file = opt('--out', '');
  if (file) fs.writeFileSync(file, JSON.stringify({ summary, out }, null, 2));
  console.log(JSON.stringify(summary, null, 2));
}

if (process.env.BVN_CHILD === 'B') childB().catch(e => { console.error(e); process.exit(1); });
else if (require.main === module) main().catch(e => { console.error(e); process.exit(1); });
